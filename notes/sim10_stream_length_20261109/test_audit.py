"""Negative acceptance checks on copies of native sweep receipts."""
import hashlib,json,sys,tempfile,unittest
from pathlib import Path
from audit import audit
SOURCE=Path(sys.argv.pop(1))
print('test_audit.py SHA256',hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),flush=True)
class Audit(unittest.TestCase):
    def setUp(self):
        self.tmp=tempfile.TemporaryDirectory();self.root=Path(self.tmp.name)
        for p in SOURCE.glob('*.json'):(self.root/p.name).write_bytes(p.read_bytes())
    def tearDown(self):self.tmp.cleanup()
    def mutate(self,fn):
        p=self.root/'03-s2-n100000.json';r=json.loads(p.read_text());fn(r);p.write_text(json.dumps(r))
    def rejects(self,fn,pattern):
        self.mutate(fn)
        with self.assertRaisesRegex(ValueError,pattern):audit(self.root)
    def test_native(self):self.assertEqual(audit(self.root)['status'],'pass')
    def test_cache(self):self.rejects(lambda r:r['measurement']['initial_cache'][0].update(resident_pages=1),'Cold gate')
    def test_rate(self):self.rejects(lambda r:r.update(gib_s=r['gib_s']+1),'Rates')
    def test_partition(self):self.rejects(lambda r:r['rows'][2]['timestamps'].pop(),'Global partition')
    def test_callback(self):self.rejects(lambda r:r['rows'][2]['callbacks'].pop(),'Callback identity')
    def test_gpu(self):self.rejects(lambda r:r['rows'][2]['device'].update(pci='wrong'),'GPU identity')
    def test_peer(self):self.rejects(lambda r:r['rows'][2]['drain'][0].update(peers=2),'Drain/peer')
    def test_io(self):self.rejects(lambda r:r['rows'][2]['io'].update(completed_requests=0),'I/O count')
    def test_histogram(self):self.rejects(lambda r:r['rows'][2]['io']['read_size_histogram'].clear(),'I/O histogram')
    def test_pressure(self):self.rejects(lambda r:r['rows'][2]['io'].update(pressure_drains=1),'Pressure/CPU')
    def test_cpu(self):self.rejects(lambda r:r['rows'][2].update(cpu_reads=1),'Pressure/CPU')
    def test_streams(self):
        def change(r):
            for c in r['rows'][2]['callbacks']:c['stream']=1
        self.rejects(change,'Execution streams')
    def test_bracket(self):self.rejects(lambda r:r['measurement']['diagnostic_after'].update(monotonic=0),'Diagnostic bracket')
    def test_settings(self):self.rejects(lambda r:r['framework'].update(streams=1),'Framework settings')
    def metadata(self,name,fn,pattern):
        p=self.root/name;r=json.loads(p.read_text());fn(r);p.write_text(json.dumps(r))
        with self.assertRaisesRegex(ValueError,pattern):audit(self.root)
    def test_source_provenance(self):self.metadata('provenance.json',lambda r:r['source_sha256'].clear(),'Source provenance')
    def test_staged_set(self):self.metadata('provenance.json',lambda r:r['staged'].pop(),'Staged file set')
    def test_fixture_identity(self):self.metadata('inputs.json',lambda r:r['timestamps'].__setitem__(0,0),'Fixture identity')
    def test_matrix(self):self.metadata('complete.json',lambda r:r['cases'].pop(),'Case matrix')
    def test_cleanup(self):self.metadata('cleanup.json',lambda r:r.update(processes_exited=False),'Incomplete sweep/cleanup')
    def test_timer(self):self.rejects(lambda r:r['measurement'].update(seconds=r['seconds']+1),'Timer identity')
    def test_event_setting(self):self.rejects(lambda r:r['settings'].update(events=10000),'Case identity')
    def test_stream_setting(self):self.rejects(lambda r:r['settings'].update(streams=1),'Case identity')
    def test_runtime(self):self.rejects(lambda r:r['rows'][2]['runtime_files'].clear(),'Frozen runtime')
    def test_helper(self):self.rejects(lambda r:r['rows'][0]['timestamps'].append(0),'Helper data')
    def test_callback_size(self):self.rejects(lambda r:r['rows'][2]['callbacks'][0].update(size=99),'Callback sizes/histogram')
    def test_mode(self):self.rejects(lambda r:r['measurement'].update(mode='network cold'),'Measurement mode')
    def test_mask(self):self.rejects(lambda r:r['rows'][0].update(mask='GPU-wrong'),'Rank GPU masks')
    def test_job(self):self.rejects(lambda r:r.update(job='different'),'Job identity')
    def test_admission(self):self.rejects(lambda r:r['rows'][2]['admission'][0].update(capacity=0),'Admission budget')
    def test_retirement(self):self.rejects(lambda r:r['rows'][2].update(cleanup_complete=False),'Cleanup/MPI')
    def test_native_acceptance(self):self.metadata('validation.json',lambda r:r.update(status='fail'),'Native input acceptance')
    def test_effective_io(self):self.rejects(lambda r:r['rows'][2]['device']['effective'].update(auto_direct_io_read=True),'GPU identity|KvikIO settings')
    def test_compat(self):self.rejects(lambda r:r['rows'][2]['device'].update(compat_mode='OFF'),'GPU identity|KvikIO settings')
    def test_smd(self):self.rejects(lambda r:r['framework'].update(smd_events=1),'Framework settings')
    def test_bulk(self):self.rejects(lambda r:r['framework'].update(bulk_target_bytes=1),'Framework settings')
    def test_affinity(self):self.rejects(lambda r:r['rows'][2]['affinity'].pop(),'CPU/runtime changed')
    def test_numa(self):self.rejects(lambda r:r['rows'][2].update(numa_policy='local'),'Placement')
    def test_host(self):self.rejects(lambda r:r.update(host='wrong'),'Host changed')
    def test_mpi(self):self.rejects(lambda r:r['rows'][2].update(mpi='wrong'),'Cleanup/MPI')
    def test_bd_mask(self):self.rejects(lambda r:r['rows'][2].update(mask=''),'Rank GPU masks')
    def test_mount(self):self.metadata('provenance.json',lambda r:r['mount']['filesystems'][0].update(fstype='ext4'),'Lustre measurement mode')
    def test_conditioning(self):self.rejects(lambda r:r['measurement']['conditioning'][0].update(resident_pages=1),'Cold gate')
    def test_pilot(self):self.metadata('pilot-s1.json',lambda r:r.update(bytes=0),'Case identity')
    def test_short_case(self):self.metadata('00-s1-n10000.json',lambda r:r['rows'][2]['callbacks'][0].update(size=1),'Callback sizes/histogram')
    def native_mutation(self,fn,pattern):
        path=self.root/'validation.json';r=json.loads(path.read_text());fn(r);path.write_text(json.dumps(r))
        p=self.root/'provenance.json';r=json.loads(p.read_text());r['validation_sha256']=hashlib.sha256(path.read_bytes()).hexdigest();p.write_text(json.dumps(r))
        with self.assertRaisesRegex(ValueError,pattern):audit(self.root)
    def test_validation_status(self):self.native_mutation(lambda r:r.update(status='fail'),'Native input acceptance')
    def test_validation_hash(self):self.native_mutation(lambda r:r['files'][0].update(sha256='wrong'),'Native file hashes')
    def test_validation_streams(self):self.native_mutation(lambda r:r['streams'][0].update(events=1),'Native stream counts')
if __name__=='__main__':unittest.main()
